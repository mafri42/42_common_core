#include "ft_printf.h"

int	ft_un_putnbr(int nb)
{
	char	c;
	int		i;

	i = 0;
	if (nb >= 10)
	{
		ft_putnbr(nb / 10);
		ft_putnbr(nb % 10);
	}
	else
	{
		c = nb + '0';
		i += write(0, &c, 1);
	}
	return (i);
}
